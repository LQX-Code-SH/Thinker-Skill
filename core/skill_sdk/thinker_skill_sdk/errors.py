"""统一错误码。

技能只产出 ``code``，面向用户的 ``msg`` 由 skill_runtime 出口按
``configs/errors.yaml`` 模板生成。前缀即类别：
``PERCEPTION_ / MOTION_ / NAV_ / PRECOND_ / SAFETY_ / INPUT_ / SYS_``。
"""


class ErrorCode:
    """错误码常量（与《接口文档》附录 A 一一对应）。"""

    OK = "OK"

    # 感知
    PERCEPTION_OBJECT_NOT_FOUND = "PERCEPTION_OBJECT_NOT_FOUND"
    PERCEPTION_TIMEOUT = "PERCEPTION_TIMEOUT"
    PERCEPTION_UNAVAILABLE = "PERCEPTION_UNAVAILABLE"
    PERCEPTION_POSE_INVALID = "PERCEPTION_POSE_INVALID"

    # 运控
    MOTION_GRASP_FAILED = "MOTION_GRASP_FAILED"
    MOTION_IK_UNREACHABLE = "MOTION_IK_UNREACHABLE"
    MOTION_TIMEOUT = "MOTION_TIMEOUT"
    MOTION_COLLISION_RISK = "MOTION_COLLISION_RISK"
    MOTION_NOT_READY = "MOTION_NOT_READY"

    # 导航
    NAV_TARGET_UNREACHABLE = "NAV_TARGET_UNREACHABLE"
    NAV_TIMEOUT = "NAV_TIMEOUT"
    NAV_MAP_NOT_READY = "NAV_MAP_NOT_READY"
    NAV_LOCATION_LOST = "NAV_LOCATION_LOST"

    # 前置状态
    PRECOND_NOT_HOLDING = "PRECOND_NOT_HOLDING"
    PRECOND_ALREADY_HOLDING = "PRECOND_ALREADY_HOLDING"
    PRECOND_BODY_BUSY = "PRECOND_BODY_BUSY"
    PRECOND_CAPABILITY_MISSING = "PRECOND_CAPABILITY_MISSING"

    # 安全
    SAFETY_ESTOP_TRIGGERED = "SAFETY_ESTOP_TRIGGERED"
    SAFETY_FORCE_LIMIT = "SAFETY_FORCE_LIMIT"
    SAFETY_STUCK_DETECTED = "SAFETY_STUCK_DETECTED"
    SAFETY_SPACE_VIOLATION = "SAFETY_SPACE_VIOLATION"

    # 输入
    INPUT_INVALID_PARAMS = "INPUT_INVALID_PARAMS"
    INPUT_UNSUPPORTED_COMMAND = "INPUT_UNSUPPORTED_COMMAND"

    # 系统
    SYS_CANCELLED = "SYS_CANCELLED"
    SYS_TIMEOUT = "SYS_TIMEOUT"
    SYS_INTERNAL_ERROR = "SYS_INTERNAL_ERROR"
    SYS_DEPENDENCY_MISSING = "SYS_DEPENDENCY_MISSING"
    SYS_CONFIG_ERROR = "SYS_CONFIG_ERROR"
